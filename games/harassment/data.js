  const ENDING_IDS = ['E1', 'E2', 'E3', 'E4', 'E5', 'E6', 'E7'];

  /* ---------- パラメータエンジン ---------- */

  const ROUTE_PARAM = { kyoken: 'R', kanchigai: 'M', hounin: 'G', shinrai: null };

  function newState() { return { R: 0, M: 0, T: 0, G: 0, H: 0, D: 0 }; }

  function applyFx(state, fx, route) {
    for (const k of ['R', 'M', 'T', 'G', 'H', 'D']) if (fx[k]) state[k] += fx[k];
    if (fx.repair && route) {
      const p = ROUTE_PARAM[route];
      if (p) state[p] = Math.max(0, state[p] - fx.repair);
    }
  }

  function decideRoute(state) {
    if (state.M >= 4) return 'kanchigai';
    if (state.R >= 5) return 'kyoken';
    if (state.G >= 4) return 'hounin';
    return 'shinrai';
  }

  /* 15スロットの選択列（内部ID）からプレイ全体を再計算する。
     ゲーム本体・復号ページ・テストの全てがこの1本を使う（ロジックの分裂防止） */
  function simulate(choices) {
    const state = newState();
    const log = [];
    // Q1-Q10
    for (let i = 0; i < 10; i++) {
      const q = COMMON1[i]; const opt = q.options[choices[i]];
      applyFx(state, opt.fx, null);
      log.push({ q, opt });
    }
    const route = decideRoute(state);
    // Q11
    const q11 = Q11[route]; const o11 = q11.options[choices[10]];
    applyFx(state, o11.fx, route); log.push({ q: q11, opt: o11 });
    // Q12
    const o12 = Q12.options[choices[11]];
    applyFx(state, o12.fx, route); log.push({ q: Q12, opt: o12 });
    // Q13
    const o13 = Q13.options[choices[12]];
    applyFx(state, o13.fx, route); log.push({ q: Q13, opt: o13 });
    // Q14（3択・決定打はkey0、信頼ルートのベスト条件はkey1）
    const q14 = Q14[route]; const o14 = q14.options[choices[13]];
    applyFx(state, o14.fx, route); log.push({ q: q14, opt: o14 });
    // Q15
    const o15 = Q15.options[choices[14]];
    applyFx(state, o15.fx, route); log.push({ q: Q15, opt: o15 });

    // エンディング判定（バッド確定はルート突入と同じ閾値。Q13修復-2で下回れば回避可能）
    let ending;
    if (route === 'kyoken'    && o14.decisive && state.R >= 5) ending = 'E3';
    else if (route === 'kanchigai' && o14.decisive && state.M >= 4) ending = 'E4';
    else if (route === 'hounin'    && o14.decisive && state.G >= 4) ending = 'E5';
    else if (state.H >= 4) ending = 'E6';
    else if (route === 'shinrai' && o14.best && state.T >= 6 &&
             state.R <= 2 && state.M <= 1 && state.G <= 1) ending = 'E1';
    // リスクを抱えたまま決定打だけ避けた場合はダークノーマル（何も起きなかった≠無事だった）
    else if (state.R >= 5 || state.M >= 4 || state.G >= 4) ending = 'E7';
    else ending = 'E2';

    return { state, route, ending, log };
  }

  /* ---------- 結果コード ---------- */
  // Crockford Base32（紛らわしい I L O U を除外）
  const B32 = '0123456789ABCDEFGHJKMNPQRSTVWXYZ';

  function encodeCode(choices) {
    const sim = simulate(choices);
    let c = 0;
    for (let i = 14; i >= 0; i--) c = c * 3 + choices[i];
    const n = (c * 4 + ROUTE_IDS.indexOf(sim.route)) * 8 + ENDINGS[sim.ending].no;
    let s = '', v = n;
    for (let i = 0; i < 6; i++) { s = B32[v % 32] + s; v = Math.floor(v / 32); }
    const check = B32[n % 31];
    const raw = s + check;
    return raw.slice(0, 4) + '-' + raw.slice(4);
  }

  function decodeCode(text) {
    const raw = (text || '').toUpperCase().replace(/[^0-9A-Z]/g, '')
      .replace(/O/g, '0').replace(/[IL]/g, '1');
    if (raw.length !== 7) return { error: 'コードは英数字7文字（例: K7XM-2PQ）です' };
    let n = 0;
    for (let i = 0; i < 6; i++) {
      const d = B32.indexOf(raw[i]);
      if (d < 0) return { error: '使用できない文字が含まれています' };
      n = n * 32 + d;
    }
    if (B32[n % 31] !== raw[6]) return { error: 'チェック文字が一致しません。コードの写し間違いの可能性があります' };
    const ending = n % 8; let v = Math.floor(n / 8);
    const route = v % 4; v = Math.floor(v / 4);
    const choices = [];
    for (let i = 0; i < 15; i++) { choices.push(v % 3); v = Math.floor(v / 3); }
    // 全15問が3択になったため、base-3のデコード値(0-2)はそのまま有効。
    // 整合性はチェック文字と下のsimulate照合で担保する
    const sim = simulate(choices);
    if (ROUTE_IDS.indexOf(sim.route) !== route || ENDINGS[sim.ending].no !== ending)
      return { error: 'コードの整合性が取れません（改変された可能性があります）' };
    return { choices, sim };
  }

  return { META, ROUTES, ROUTE_IDS, ROUTE_PARAM, COMMON1, Q11, Q12, Q12_INTRO, Q13, Q13_PARTNER,
           Q14, Q15, MIYOSHI_EPILOGUE, ENDINGS, ENDING_IDS, simulate, encodeCode, decodeCode };
